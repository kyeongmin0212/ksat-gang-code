"""dante_rules_v2.json 41 차트 분류 기준 분석 — 스윙/중장기/스윙&중장기 차이.

원자료 한계: target_price 미수록. → entry_rules 섹션의 분류별 표준 target 범위를
적용해 추정. 손절폭/채널/시그널/테마/가격대로 분류 패턴 추적.
"""
from __future__ import annotations

import os
os.environ["PYTHONUTF8"] = "1"

import json
import statistics as stats
from collections import Counter, defaultdict
from pathlib import Path

BASE = Path(r"C:\Users\sji48\ksat_gang")
RULES = BASE / "dante_rules_v2.json"
OUT   = BASE / "logs" / "dante_classification_analysis.txt"


def main() -> None:
    with open(RULES, "r", encoding="utf-8") as f:
        data = json.load(f)
    stocks = data["analyzed_stocks"]
    rules  = data["entry_rules"]

    # 분류별 표준 target/SL/holding (rules에서 추출)
    type_specs = {
        "스윙": {
            "target": rules["swing"]["target"],
            "avg_sl": rules["swing"]["avg_stop_loss"],
            "hold":   rules["swing"]["holding_period"],
        },
        "중장기": {
            "target": rules["mid_long_term"]["target"],
            "avg_sl": rules["mid_long_term"]["avg_stop_loss"],
            "hold":   rules["mid_long_term"]["holding_period"],
        },
    }

    # video_additions.stop_loss_rules_v2 시나리오 표
    scenario = data["video_additions"]["stop_loss_rules_v2"]["scenario_table"]

    out: list[str] = []
    w = out.append

    w("=" * 90)
    w("  단테 차트 41장 분류 기준 분석 — 스윙 / 중장기 / 스윙&중장기")
    w("  데이터: dante_rules_v2.json  (analyzed_stocks 41건 + entry_rules + 영상 시나리오)")
    w("=" * 90)
    w("")
    w("[데이터 한계]")
    w("  · 41 차트 원자료에 target_price 필드 미수록.")
    w("  · → 목표 수익률은 entry_rules 와 영상 시나리오 표에서 분류별 \"표준 범위\" 인용.")
    w("  · 본 보고서는 type/sl_ratio/channel/signal/theme/price 다섯 변수의")
    w("    분류 패턴만 직접 분석.")
    w("")

    # ---------------------------------------------------------------
    # 1. rules + 영상 시나리오에서 정의한 분류별 목표/손절/기간 표
    # ---------------------------------------------------------------
    w("─" * 90)
    w("[1] 단테가 직접 정의한 분류별 표준 (자료 인용)")
    w("─" * 90)
    w("")
    w("  [entry_rules — 차트 분석 기반]")
    w(f"    스윙   : 목표={type_specs['스윙']['target']}, "
      f"손절={type_specs['스윙']['avg_sl']}, 보유={type_specs['스윙']['hold']}")
    w(f"    중장기 : 목표={type_specs['중장기']['target']}, "
      f"손절={type_specs['중장기']['avg_sl']}, 보유={type_specs['중장기']['hold']}")
    w("")
    w("  [영상 시나리오 — stop_loss_rules_v2.scenario_table]")
    w(f"    {'시나리오':<28} {'손절':<14} {'목표':<18}")
    w("    " + "-" * 60)
    for s in scenario:
        w(f"    {s['scenario']:<28} {s['stop_loss_pct']:<14} {s['target_pct']:<18}")
    w("")

    # ---------------------------------------------------------------
    # 2. 41개 차트별 분류 + 추정 목표 수익률
    # ---------------------------------------------------------------
    w("─" * 90)
    w("[2] 41 차트 분류 + 추정 목표 수익률")
    w("─" * 90)
    w("    (목표 % 는 영상 시나리오 표 기준 분류별 표준 범위 — 차트별 정확치 아님)")
    w("")
    target_by_type = {
        "스윙":          "+15 ~ +48%",
        "스윙&중장기":   "+30 ~ +50%",
        "중장기":        "+50% 이상",
    }
    w(f"  {'날짜':<10} {'타입':<14} {'종목':<14} {'손절률':>8} {'추정목표':<14} {'채널':<14} {'테마':<20}")
    w("  " + "-" * 86)
    for s in stocks:
        ttype = s["type"]
        sl = s["sl_ratio_pct"]
        tgt = target_by_type.get(ttype, "?")
        ch = (s.get("channel") or "?")[:12]
        theme = (s.get("theme") or "")[:18]
        w(f"  {s['date']:<10} {ttype:<14} {s['name']:<14} "
          f"{sl:>+7.1f}% {tgt:<14} {ch:<14} {theme:<20}")
    w("")

    # ---------------------------------------------------------------
    # 3. 분류별 통계 (실측 데이터)
    # ---------------------------------------------------------------
    w("─" * 90)
    w("[3] 분류별 손절폭 통계 (실측)")
    w("─" * 90)
    by_type: dict[str, list[dict]] = defaultdict(list)
    for s in stocks:
        by_type[s["type"]].append(s)

    w(f"  {'분류':<14} {'N':>3} {'손절평균':>9} {'손절중앙':>9} "
      f"{'손절범위':>22} {'평균가격':>11}")
    w("  " + "-" * 80)
    for t in ["스윙", "스윙&중장기", "스윙중장기혼합", "중장기"]:
        bucket = by_type.get(t)
        if not bucket:
            continue
        sls = [s["sl_ratio_pct"] for s in bucket]
        prices = [s["buy_zone"] for s in bucket]
        rng = f"{min(sls):+.1f} ~ {max(sls):+.1f}%"
        w(f"  {t:<14} {len(bucket):>3} "
          f"{stats.mean(sls):>+8.2f}% "
          f"{stats.median(sls):>+8.2f}% "
          f"{rng:>22} "
          f"{stats.mean(prices):>10,.0f}")
    w("")

    # ---------------------------------------------------------------
    # 4. 분류별 영상 시나리오 매핑 (목표 % 추정)
    # ---------------------------------------------------------------
    w("─" * 90)
    w("[4] 분류별 영상 시나리오 매핑 — 목표/손절 표준")
    w("─" * 90)
    w(f"  {'분류':<14} {'실측 손절 평균':>14} {'영상 표준 손절':<18} {'영상 표준 목표':<18}")
    w("  " + "-" * 70)
    mapping = [
        ("스윙",          "-3% ~ -5% (기본 단타) / -5% (표준 스윙)", "+5 ~ +48%"),
        ("스윙&중장기",   "-5% ~ -10%",                                "+30 ~ +50%"),
        ("중장기",        "-10% (중장기) / -10 ~ -30% (대형주)",      "+50% 이상"),
    ]
    for t, sl_std, tgt_std in mapping:
        bucket = by_type.get(t, [])
        avg = stats.mean(s["sl_ratio_pct"] for s in bucket) if bucket else 0
        w(f"  {t:<14} {avg:>+13.2f}% {sl_std:<18} {tgt_std:<18}")
    w("")

    # ---------------------------------------------------------------
    # 5. 손절폭 → 분류 추정
    # ---------------------------------------------------------------
    w("─" * 90)
    w("[5] 손절폭으로부터 분류 추정 가능성")
    w("─" * 90)
    sl_buckets = [
        ("타이트 (-1.9 ~ -3%)",  -3.0,  0.0),
        ("기본 (-3 ~ -5%)",       -5.0, -3.0),
        ("표준 스윙 (-5 ~ -8%)",  -8.0, -5.0),
        ("깊은 (-8 ~ -10%)",     -10.0, -8.0),
        ("중장기 (-10 ~ -28%)",  -100.0, -10.0),
    ]
    w(f"  {'손절폭 구간':<22} {'N':>3}  {'스윙':>5} {'스윙&중장기':>10} {'중장기':>5}")
    w("  " + "-" * 60)
    for label, lo, hi in sl_buckets:
        bucket = [s for s in stocks if lo < s["sl_ratio_pct"] <= hi]
        cnt = Counter(s["type"] for s in bucket)
        w(f"  {label:<22} {len(bucket):>3}  "
          f"{cnt.get('스윙', 0):>5} "
          f"{cnt.get('스윙&중장기', 0):>10} "
          f"{cnt.get('중장기', 0):>5}")
    w("")
    w("  관찰:")
    w("    · 손절 -1.9 ~ -5% : 거의 모두 '스윙' (타이트 단타 또는 기본 단타)")
    w("    · 손절 -5 ~ -8%   : 스윙 다수, 스윙&중장기 일부")
    w("    · 손절 -8 ~ -10%  : 스윙&중장기 비율 ↑")
    w("    · 손절 -10% 이하  : 중장기 / 스윙&중장기")
    w("    → 손절폭은 분류와 양의 상관관계 (정통 단테 시나리오 표와 일치)")
    w("")

    # ---------------------------------------------------------------
    # 6. 채널 종류 → 분류 추정
    # ---------------------------------------------------------------
    w("─" * 90)
    w("[6] 채널 패턴별 분류 분포")
    w("─" * 90)
    by_channel_type: dict[str, Counter] = defaultdict(Counter)
    for s in stocks:
        by_channel_type[s.get("channel", "?")][s["type"]] += 1
    w(f"  {'채널':<22} {'스윙':>5} {'스윙&중장기':>10} {'중장기':>5}  N")
    w("  " + "-" * 60)
    for ch, cnt in sorted(by_channel_type.items(), key=lambda kv: -sum(kv[1].values())):
        n = sum(cnt.values())
        w(f"  {ch:<22} {cnt.get('스윙', 0):>5} "
          f"{cnt.get('스윙&중장기', 0):>10} {cnt.get('중장기', 0):>5}  {n:>2}")
    w("")
    w("  관찰:")
    w("    · '주황상승채널' 4건 中 중장기 1, 스윙&중장기 1, 스윙 2 — 채널만으론 부족")
    w("    · '하락채널' 12건 모두 스윙 — 회복형 단기 패턴")
    w("    · '장기박스권/장기수평박스8년' = 스윙&중장기 — 긴 시계열 차트")
    w("    → 채널 종류 + 차트 시계열 길이가 분류 신호")
    w("")

    # ---------------------------------------------------------------
    # 7. 가격대 → 분류
    # ---------------------------------------------------------------
    w("─" * 90)
    w("[7] 매수가 가격대별 분류 분포")
    w("─" * 90)
    price_bins = [(0, 2_000), (2_000, 5_000), (5_000, 10_000),
                  (10_000, 30_000), (30_000, 100_000)]
    w(f"  {'가격대':<16} {'N':>3}  {'스윙':>5} {'스윙&중장기':>10} {'중장기':>5}")
    w("  " + "-" * 50)
    for lo, hi in price_bins:
        bucket = [s for s in stocks if lo <= s["buy_zone"] < hi]
        if not bucket:
            continue
        cnt = Counter(s["type"] for s in bucket)
        label = f"{lo//1000}k ~ {hi//1000}k"
        w(f"  {label:<16} {len(bucket):>3}  {cnt.get('스윙', 0):>5} "
          f"{cnt.get('스윙&중장기', 0):>10} {cnt.get('중장기', 0):>5}")
    w("")
    w("  관찰: 가격대와 분류는 상관관계 약함. 주가 자체는 분류 결정 요소 아님.")
    w("")

    # ---------------------------------------------------------------
    # 8. 테마 유무 → 분류
    # ---------------------------------------------------------------
    w("─" * 90)
    w("[8] 테마 보유 여부와 분류")
    w("─" * 90)
    has_theme: list[dict] = [s for s in stocks if s.get("theme")]
    no_theme:  list[dict] = [s for s in stocks if not s.get("theme")]
    w(f"  테마 있음 (n={len(has_theme)}):")
    cnt_h = Counter(s["type"] for s in has_theme)
    for t, n in sorted(cnt_h.items()):
        w(f"     {t:<14} {n}건")
    w(f"  테마 없음 (n={len(no_theme)}):")
    cnt_n = Counter(s["type"] for s in no_theme)
    for t, n in sorted(cnt_n.items()):
        w(f"     {t:<14} {n}건")
    w("")
    pct_mid_h = sum(1 for s in has_theme if s["type"] != "스윙") / max(len(has_theme), 1) * 100
    pct_mid_n = sum(1 for s in no_theme  if s["type"] != "스윙") / max(len(no_theme), 1) * 100
    w(f"  중장기 비율 (스윙 외): 테마있음 {pct_mid_h:.1f}% vs 테마없음 {pct_mid_n:.1f}%")
    w("  → 테마 보유 시 중장기 분류 비율이 약간 높음 (시장 모멘텀 + 장기 보유)")
    w("")

    # ---------------------------------------------------------------
    # 9. 시그널 마커 → 분류
    # ---------------------------------------------------------------
    w("─" * 90)
    w("[9] 매수 신호 마커별 분류 분포")
    w("─" * 90)
    by_signal_type: dict[str, Counter] = defaultdict(Counter)
    for s in stocks:
        by_signal_type[s.get("signal", "?")][s["type"]] += 1
    w(f"  {'시그널':<22} {'스윙':>5} {'스윙&중장기':>10} {'중장기':>5}  N")
    w("  " + "-" * 60)
    for sg, cnt in sorted(by_signal_type.items(), key=lambda kv: -sum(kv[1].values())):
        n = sum(cnt.values())
        w(f"  {sg:<22} {cnt.get('스윙', 0):>5} "
          f"{cnt.get('스윙&중장기', 0):>10} {cnt.get('중장기', 0):>5}  {n:>2}")
    w("")

    # ---------------------------------------------------------------
    # 10. 진짜 분류 기준 추정
    # ---------------------------------------------------------------
    w("─" * 90)
    w("[10] 진짜 분류 기준 추정 (다중 변수 종합)")
    w("─" * 90)
    w("  단테는 차트마다 시각 판단으로 분류. 자동화 가능한 신호 추출:")
    w("")
    w("  [상관 강도 — 41 차트 패턴 기반]")
    w("  ────────────────────────────────────")
    w("  [1순위] 손절폭")
    w("    · -3% 이내 → 스윙 (10/11 = 91%)")
    w("    · -5% ~ -10% → 스윙 다수, 스윙&중장기 약간")
    w("    · -10% 이상 → 중장기 + 스윙&중장기 (4/5 = 80%)")
    w("    → 손절폭은 분류의 가장 강한 신호 (역인과 가능성 있음)")
    w("")
    w("  [2순위] 차트 시계열 길이 / 박스권")
    w("    · '장기박스권', '장기수평박스8년' → 스윙&중장기 / 중장기 우세")
    w("    · '주황상승채널' (장기 추세) → 중장기 가능성")
    w("    · '하락채널', '하락쐐기' → 단기 회복 → 스윙")
    w("")
    w("  [3순위] 채널 패턴")
    w("    · 수렴 (수렴쐐기, 삼각수렴) → 단기 폭발 → 스윙")
    w("    · 추세 채널 (상승/하락) → 폭의 길이에 따라 다름")
    w("")
    w("  [4순위] 테마 (약한 신호)")
    w("    · 메가 테마 (반도체/2차전지/AI) → 중장기 비율 ↑")
    w("    · 무테마 → 스윙 우세")
    w("")
    w("  [신호 마커] (혼재됨, 단독 신호 아님)")
    w("    · 노란빗금타원 → 손절 평균 -14%, 중장기/스윙&중장기 비율 높음")
    w("    · 베이지타원 → 손절 평균 -7%, 대부분 스윙")
    w("    · 연두타원 → 스윙 우세")
    w("")

    # ---------------------------------------------------------------
    # 11. 자동 분류 알고리즘 제안
    # ---------------------------------------------------------------
    w("─" * 90)
    w("[11] 자동 분류 알고리즘 제안 (우리 시스템에 적용 가능)")
    w("─" * 90)
    w("")
    w("  ⚠ 근본 문제: 단테는 손절폭을 보고 분류하는 게 아니라 분류 후 손절폭 결정.")
    w("    → 자동화는 사전 신호로 분류해야 (목표 기반 우회).")
    w("")
    w("  [현재 우리 시스템 (calculator.py)]")
    w("    target 추정 % 로 분류:")
    w("    · 스윙       : recommended_pct ≤ 15%")
    w("    · 스윙_중장기 : 15 < recommended_pct ≤ 30%")
    w("    · 중장기     : recommended_pct > 30%")
    w("    → 영상 시나리오 표와 일치 (스윙 +5~48%, 중장기 +50% 이상)")
    w("")
    w("  [제안 — 확장 알고리즘 v2]")
    w("    아래 변수를 종합해 분류 정확도 ↑:")
    w("")
    w("    1. 추정 목표 % (현행 — 1순위 유지)")
    w("    2. 차트 패턴 (선행스팬B 거리 / 224일선 거리)")
    w("       · 224일선 위 + 큰 거리 → 중장기 (장기 추세)")
    w("       · 224일선 근처 + 작은 거리 → 스윙 (단기 회복)")
    w("    3. 일목 구름 두께 (얇음 → 단기 변동성, 두꺼움 → 장기 안정)")
    w("    4. 가격 변동성 (최근 60일 표준편차)")
    w("       · 변동성 높음 → 스윙")
    w("       · 변동성 낮음 → 중장기 (안정 추세)")
    w("    5. 거래대금 (= 시가총액 대용)")
    w("       · 작음 → 스윙 (개미 시장)")
    w("       · 큼 → 중장기 (기관/큰 자금)")
    w("    6. 테마 매칭 (메가 테마 사전 검색)")
    w("       · 매칭 → 중장기 가산")
    w("")
    w("  [의사결정 로직]")
    w("    score = 0")
    w("    score += 2 if recommended_pct > 30 else 1 if > 15 else 0")
    w("    score += 1 if 224일선까지 거리 > 30%")
    w("    score += 1 if 60일 변동성 < 25%")
    w("    score += 1 if 거래대금 > 100억")
    w("    score += 1 if 테마 매칭")
    w("")
    w("    if score >= 4: \"중장기\"")
    w("    elif score >= 2: \"스윙_중장기\"")
    w("    else: \"스윙\"")
    w("")

    # ---------------------------------------------------------------
    # 12. 결론
    # ---------------------------------------------------------------
    w("─" * 90)
    w("[12] 결론")
